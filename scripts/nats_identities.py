#!/usr/bin/env python3
"""Render and check the per-service NATS identities (FEATURES A19).

Source of truth: platform/nats/identities/identities.yaml (no credentials).

Commands
  values  [--check]                 write (or verify) platform/nats/values.identities.stage-{a1,a2,b}.template.yaml
  check                             invariants + generated values file up to date (CI)
  gen-passwords --out FILE [--users a,b]
                                    random passwords as JSON {user: password}, mode 0600.
                                    Never write FILE inside the repository.
  conf --passwords FILE [--stage A1|A2|B|C] [--hash] [--out FILE]
                                    nats.conf JSON fragment (system_account + accounts) with the
                                    passwords (or bcrypt hashes) filled in; used by the tests
  live --live-conf FILE --passwords FILE [--stage A1|A2|B|C] --out FILE
                                    full new nats.conf for the nats-config ConfigMap: the live
                                    config with accounts replaced and (from A2) leafnodes.authorization
                                    removed. Users already in the live config (sys, monitor,
                                    onemind, leaf_tak) keep their live password hashes; new users
                                    get bcrypt hashes of the passwords in FILE.
  leaf-local --user U               the local-account fragment of U's leaf sidecar (no credentials):
                                    a local user with U's allow lists, so the sidecar itself refuses
                                    a forbidden publish with a Permissions Violation (used by permtest)
  leaf-conf --user U --passwords FILE --out FILE
                                    the full leaf.conf for U's sidecar (to seal as a SecretKey),
                                    written outside the repository
  secrets                           table of where each user's password must be sealed

Stages (platform/nats/IDENTITIES.md):
  A1 new accounts and users next to the shared ones; legacy users unrestricted; leaf_tak stays in
     leafnodes.authorization. Config reload only.
  A2 A1 plus leafnodes.authorization removed and leaf_tak moved into ONEMIND, so leaf users can
     carry permissions. Needs a pod restart (leafnode users are not reloadable).
  B  A2 plus the deny lists on the legacy users (onemind, leaf_tak).
  C  legacy users removed (SYS users stay).
"""
from __future__ import annotations

import argparse
import copy
import json
import os
import re
import secrets
import shutil
import subprocess
import sys
import urllib.parse
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "platform/nats/identities/identities.yaml"
VALUES = {
    "A1": ROOT / "platform/nats/values.identities.stage-a1.template.yaml",
    "A2": ROOT / "platform/nats/values.identities.stage-a2.template.yaml",
    "B": ROOT / "platform/nats/values.identities.stage-b.template.yaml",
}
STAGES = ("A1", "A2", "B", "C")
# Users that live in leafnodes.authorization (not in an account) at stage A1, exactly as today.
LEAF_AUTH_A1 = ("leaf_tak",)

HEADER = """\
# GENERATED by scripts/nats_identities.py from platform/nats/identities/identities.yaml.
# Do not edit by hand; edit the spec and run `python3 scripts/nats_identities.py values`.
#
# Helm values for the per-service NATS identities (FEATURES A19), stage {stage}. Layer it
# after values.template.yaml / values.secret.yaml. Every __<USER>_PW__ is a placeholder: the
# real value is a bcrypt hash that exists only in the owner's gitignored values.secret.yaml
# and in the live nats-config ConfigMap; the plaintext goes into a SealedSecret per workload.
# The live release must NOT be changed with `helm upgrade` (it would overwrite the Git-owned
# StatefulSet, platform/nats/OPERATIONS.md); activation patches the ConfigMap instead:
# platform/nats/IDENTITIES.md.
"""

JS_INFO = "$JS.API.INFO"


def load_spec() -> dict:
    with SPEC.open() as f:
        return yaml.safe_load(f)


def placeholder(user: str) -> str:
    return "__" + user.upper().replace("-", "_") + "_PW__"


def _consume(s: str) -> list[str]:
    return [
        f"$JS.API.STREAM.INFO.{s}",
        f"$JS.API.CONSUMER.CREATE.{s}",
        f"$JS.API.CONSUMER.CREATE.{s}.>",
        f"$JS.API.CONSUMER.DURABLE.CREATE.{s}.*",
        f"$JS.API.CONSUMER.INFO.{s}.*",
        f"$JS.API.CONSUMER.DELETE.{s}.*",
        f"$JS.API.CONSUMER.MSG.NEXT.{s}.*",
        f"$JS.ACK.{s}.>",
        f"$JS.FC.{s}.>",
    ]


def _get(s: str) -> list[str]:
    return [
        f"$JS.API.STREAM.INFO.{s}",
        f"$JS.API.DIRECT.GET.{s}",
        f"$JS.API.DIRECT.GET.{s}.>",
        f"$JS.API.STREAM.MSG.GET.{s}",
    ]


def expand_jetstream(js: dict | None) -> list[str]:
    if not js:
        return []
    out: list[str] = []
    if js.get("info"):
        out.append(JS_INFO)
    if js.get("names"):
        out.append("$JS.API.STREAM.NAMES")
    for s in js.get("consume", []):
        out += _consume(s)
    for s in js.get("get", []):
        out += _get(s)
    for s in js.get("delete_msg", []):
        out += [f"$JS.API.STREAM.INFO.{s}", f"$JS.API.STREAM.MSG.DELETE.{s}"]
    for b in js.get("kv_read", []) + js.get("kv_write", []):
        out += _consume(f"KV_{b}") + _get(f"KV_{b}")
    for b in js.get("kv_write", []):
        out.append(f"$KV.{b}.>")
    seen: set[str] = set()
    return [x for x in out if not (x in seen or seen.add(x))]


def user_entry(u: dict, stage: str, password: str) -> dict | None:
    """One nats.conf user entry, or None if the user is absent at this stage."""
    legacy = u.get("stage") == "legacy"
    if stage == "C" and legacy and u["account"] != "SYS":
        return None
    if stage == "A1" and u["user"] in LEAF_AUTH_A1:
        return None  # still in leafnodes.authorization (rendered by leaf_auth_a1)
    e: dict = {"user": u["user"], "password": password}
    # Legacy users get connection types from A2 on: at A1 only leafnodes.authorization users can
    # log in as leafs anyway, and A1 must not change anything for existing clients.
    if u.get("connection_types") and not (legacy and stage == "A1"):
        e["allowed_connection_types"] = list(u["connection_types"])
    perms: dict = {}
    pub = list(u.get("publish") or []) + expand_jetstream(u.get("jetstream"))
    sub = list(u.get("subscribe") or [])
    if not legacy:
        perms["publish"] = {"allow": pub if pub else ["_NO_PUBLISH_"]}
        perms["subscribe"] = {"allow": sub if sub else ["_NO_SUBSCRIBE_"]}
        ar = u.get("allow_responses")
        if ar is True:
            perms["allow_responses"] = True
        elif isinstance(ar, dict):
            perms["allow_responses"] = dict(ar)
    elif stage == "B" and u.get("stage_b"):
        sb = u["stage_b"]
        perms["publish"] = {"deny": list(sb.get("publish_deny", []))}
        perms["subscribe"] = {"deny": list(sb.get("subscribe_deny", []))}
    if perms:
        e["permissions"] = perms
    return e


def render_accounts(spec: dict, stage: str, pw) -> dict:
    accounts = copy.deepcopy(spec["accounts"])
    for a in accounts.values():
        a["users"] = []
    for u in spec["users"]:
        e = user_entry(u, stage, pw(u["user"]))
        if e is not None:
            accounts[u["account"]]["users"].append(e)
    return accounts


def leaf_auth_a1(spec: dict, pw) -> dict:
    users = [u for u in spec["users"] if u["user"] in LEAF_AUTH_A1]
    return {"users": [{"user": u["user"], "password": pw(u["user"]), "account": u["account"]} for u in users]}


def render_values(spec: dict, stage: str = "B") -> str:
    accounts = render_accounts(spec, stage, placeholder)
    cfg: dict = {}
    if stage != "A1":
        # Leaf users are account users from A2 on, so they can carry permissions (a permissions
        # block in leafnodes.authorization.users is rejected by the server). Not reloadable:
        # A2 needs a pod restart (IDENTITIES.md).
        cfg["leafnodes"] = {"merge": {"authorization": None}}
    cfg["merge"] = {"system_account": spec["system_account"], "accounts": accounts}
    doc = {"config": cfg}
    body = yaml.safe_dump(doc, sort_keys=False, width=100, default_flow_style=False)
    return HEADER.format(stage=stage) + body


def find_user(spec: dict, name: str) -> dict:
    for u in spec["users"]:
        if u["user"] == name:
            return u
    sys.exit(f"unknown user {name}")


def sidecar_local(spec: dict, name: str) -> dict:
    """Local account of a leaf user's sidecar: one password-less local user carrying exactly the
    hub user's allow lists (same render as the hub entry). The hub only advertises to a leaf the
    subjects its user may publish, so without this a forbidden publish vanishes on the spoke with
    no error and no log line; with it the sidecar answers `Permissions Violation` and logs it."""
    u = find_user(spec, name)
    sc = u.get("sidecar")
    if not sc:
        sys.exit(f"{name} has no sidecar in the spec")
    hub = user_entry(u, "B", "")
    local = {"user": sc["local_user"]}
    if "permissions" in hub:
        local["permissions"] = hub["permissions"]
    return {"accounts": {sc["account"]: {"users": [local]}}, "no_auth_user": sc["local_user"]}


def render_leaf_conf(spec: dict, name: str, password: str) -> dict:
    u = find_user(spec, name)
    sc = u["sidecar"] if u.get("sidecar") else sys.exit(f"{name} has no sidecar in the spec")
    conf = {"port": 4222, "http": 8222, "server_name": sc["server_name"]}
    conf.update(sidecar_local(spec, name))
    url = f"tls://{urllib.parse.quote(name, safe='')}:{urllib.parse.quote(password, safe='')}@{sc['remote']}"
    conf["leafnodes"] = {"remotes": [{"urls": [url], "account": sc["account"], "tls": {"ca_file": sc["ca_file"]}}]}
    return conf


def bcrypt_hash(password: str) -> str:
    nats = shutil.which("nats") or os.environ.get("NATS_CLI")
    if not nats:
        sys.exit("bcrypt needs the nats CLI on PATH (or NATS_CLI): `nats server passwd`")
    env = dict(os.environ, PASSWORD=password)  # never on the command line
    out = subprocess.run([nats, "server", "passwd", "--cost", "11"], env=env,
                         capture_output=True, text=True, check=True).stdout.strip()
    if not out.startswith("$2"):
        sys.exit("unexpected output from nats server passwd")
    return out


def read_passwords(path: str) -> dict:
    p = Path(path).resolve()
    if ROOT in p.parents:
        sys.exit(f"refusing to read a password file inside the repository: {p}")
    with p.open() as f:
        return json.load(f)


def write_private(path: str, text: str) -> None:
    p = Path(path).resolve()
    if ROOT in p.parents:
        sys.exit(f"refusing to write credentials inside the repository: {p}")
    p.parent.mkdir(parents=True, exist_ok=True)
    fd = os.open(p, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as f:
        f.write(text)


# ---------------------------------------------------------------- invariants

CMD_EXEMPT = ("cmd.map.",)


def _covers(pattern: str, subject: str) -> bool:
    """True if NATS pattern `pattern` matches the literal subject `subject`."""
    p, s = pattern.split("."), subject.split(".")
    for i, tok in enumerate(p):
        if tok == ">":
            return len(s) > i
        if i >= len(s) or (tok != "*" and tok != s[i]):
            return False
    return len(p) == len(s)


def check_invariants(spec: dict) -> list[str]:
    errs: list[str] = []
    names = [u["user"] for u in spec["users"]]
    if len(names) != len(set(names)):
        errs.append("duplicate user names")
    for u in spec["users"]:
        if u["account"] not in spec["accounts"]:
            errs.append(f"{u['user']}: unknown account {u['account']}")
        if "password" in u:
            errs.append(f"{u['user']}: a password field is not allowed in the spec")
        if u.get("stage") != "legacy" and u["account"] != "SYS":
            if "secret" not in u:
                errs.append(f"{u['user']}: missing secret location")
        pub = list(u.get("publish") or []) + expand_jetstream(u.get("jetstream"))
        if u.get("stage") == "legacy":
            continue
        for s in pub:
            if s.startswith("_INBOX"):
                errs.append(f"{u['user']}: publish on {s} lets it spoof replies; use allow_responses")
            if s.startswith("$JS.API.STREAM.CREATE") or s.startswith("$JS.API.STREAM.UPDATE") or s in ("$JS.API.>", "$JS.>", ">"):
                errs.append(f"{u['user']}: stream admin ({s}) can republish into any subject")
        if u["user"] != "policy":
            for probe in ("cmd.fleet.drone.sim-x1.goto", "cmd.mission.m1.create", "cmd.entity.e1.override", "cmd.ha.light.on"):
                if any(_covers(p, probe) for p in pub):
                    errs.append(f"{u['user']}: may publish {probe} (only policy publishes cmd.*, except cmd.map.>)")
        if u["user"] != "projector":
            for probe in ("tak.cot.inject", "tak.cot.mesh.tx"):
                if any(_covers(p, probe) for p in pub):
                    errs.append(f"{u['user']}: may publish {probe} (projector only)")
        if u["user"] != "entity" and any(_covers(p, "ent.drone.sim-x1.state") for p in pub):
            errs.append(f"{u['user']}: may publish ent.*.*.state (entity service only)")
        if u.get("sidecar") and u.get("connection_types") != ["LEAFNODE"]:
            errs.append(f"{u['user']}: a sidecar belongs to a leaf-only user (connection_types [LEAFNODE])")
        if u["account"] in ("CLIENT", "AGENTS") and u.get("jetstream"):
            errs.append(f"{u['user']}: {u['account']} has no JetStream")
        if u["account"] == "AGENTS" and any(_covers(p, "svc.policy.command.confirm") for p in pub):
            errs.append(f"{u['user']}: an agent may never reach svc.policy.*.confirm")
    for name in ("CLIENT", "AGENTS"):
        if spec["accounts"][name].get("jetstream"):
            errs.append(f"account {name} must not enable JetStream")
    ag = spec["accounts"]["AGENTS"]
    for imp in ag.get("imports", []):
        subj = (imp.get("service") or imp.get("stream") or {}).get("subject", "")
        if "confirm" in subj or subj in ("svc.policy.>", "svc.policy.*.confirm"):
            errs.append(f"AGENTS imports {subj}: agents can never confirm")
    return errs


def cmd_values(args) -> int:
    spec, rc = load_spec(), 0
    for stage, path in VALUES.items():
        text = render_values(spec, stage)
        if args.check:
            if not path.exists() or path.read_text() != text:
                print(f"{path.relative_to(ROOT)} is out of date: run python3 scripts/nats_identities.py values")
                rc = 1
            continue
        path.write_text(text)
        print(f"wrote {path.relative_to(ROOT)}")
    return rc


def cmd_check(args) -> int:
    spec = load_spec()
    errs = check_invariants(spec)
    for e in errs:
        print("ERROR:", e)
    rc = 1 if errs else 0
    args.check = True
    rc |= cmd_values(args)
    if rc == 0:
        print(f"ok: {len(spec['users'])} users, {len(spec['accounts'])} accounts, invariants hold, values file current")
    return rc


def cmd_gen_passwords(args) -> int:
    spec = load_spec()
    users = args.users.split(",") if args.users else [u["user"] for u in spec["users"]]
    pw = {u: secrets.token_urlsafe(24) for u in users}
    write_private(args.out, json.dumps(pw, indent=2) + "\n")
    print(f"wrote {len(pw)} passwords to {args.out} (0600)")
    return 0


def cmd_conf(args) -> int:
    spec = load_spec()
    pws = read_passwords(args.passwords)
    cache: dict[str, str] = {}

    def pw(user: str) -> str:
        if user not in pws:
            sys.exit(f"no password for {user} in {args.passwords}")
        if args.hash:
            cache.setdefault(user, bcrypt_hash(pws[user]))
            return cache[user]
        return pws[user]

    out = {"system_account": spec["system_account"], "accounts": render_accounts(spec, args.stage, pw)}
    if args.stage == "A1":
        out["leafnodes"] = {"authorization": leaf_auth_a1(spec, pw)}
    text = json.dumps(out, indent=2) + "\n"
    if args.out:
        write_private(args.out, text)
    else:
        sys.stdout.write(text)
    return 0


# The chart and the live ConfigMap write nats.conf as JSON with a few bare tokens that NATS
# accepts and JSON does not (sizes such as 45Gi, variables such as $SERVER_NAME). They are
# carried through as tagged strings and written back bare.
_RAW = "__natsraw__:"
_BARE = re.compile(r'^(\s*"[^"]+"\s*:\s*)([^"{\[\s][^,]*?)(\s*,?\s*)$')
_PLAIN = re.compile(r"^(-?\d+(\.\d+)?([eE][-+]?\d+)?|true|false|null)$")


def load_natsconf(text: str) -> dict:
    lines = []
    for line in text.splitlines():
        m = _BARE.match(line)
        if m and not _PLAIN.match(m.group(2).strip()):
            line = f'{m.group(1)}"{_RAW}{m.group(2).strip()}"{m.group(3)}'
        lines.append(line)
    return json.loads("\n".join(lines))


def dump_natsconf(obj: dict) -> str:
    text = json.dumps(obj, indent=2)
    return re.sub(r'"' + re.escape(_RAW) + r'([^"]*)"', r"\1", text) + "\n"


def cmd_live(args) -> int:
    spec = load_spec()
    live = load_natsconf(Path(args.live_conf).read_text())
    pws = read_passwords(args.passwords)
    existing: dict[str, str] = {}
    for acc in live.get("accounts", {}).values():
        for u in acc.get("users", []):
            existing[u["user"]] = u["password"]
    for u in (live.get("leafnodes", {}).get("authorization", {}) or {}).get("users", []):
        existing[u["user"]] = u["password"]

    def pw(user: str) -> str:
        if user in existing:
            return existing[user]
        if user not in pws:
            sys.exit(f"no password for new user {user} in {args.passwords}")
        return bcrypt_hash(pws[user])

    new = copy.deepcopy(live)
    new["system_account"] = spec["system_account"]
    new["accounts"] = render_accounts(spec, args.stage, pw)
    if "leafnodes" in new and args.stage != "A1":
        new["leafnodes"].pop("authorization", None)
    write_private(args.out, dump_natsconf(new))
    print(f"wrote {args.out}; diff it against the live config before applying (IDENTITIES.md)")
    return 0


def cmd_leaf_local(args) -> int:
    sys.stdout.write(json.dumps(sidecar_local(load_spec(), args.user), indent=2) + "\n")
    return 0


def cmd_leaf_conf(args) -> int:
    pws = read_passwords(args.passwords)
    if args.user not in pws:
        sys.exit(f"no password for {args.user} in {args.passwords}")
    conf = render_leaf_conf(load_spec(), args.user, pws[args.user])
    write_private(args.out, json.dumps(conf, indent=2) + "\n")
    print(f"wrote {args.out} (0600); seal it as key leaf.conf (platform/nats/IDENTITIES.md step 2)")
    return 0


def cmd_secrets(args) -> int:
    spec = load_spec()
    print("| user | account | stage | where the password goes |")
    print("|---|---|---|---|")
    for u in spec["users"]:
        s = u.get("secret")
        where = f"`{s['namespace']}/{s['name']}` keys `{s['user_key']}`, `{s['password_key']}`" if s else "values.secret.yaml (existing)"
        print(f"| `{u['user']}` | {u['account']} | {u.get('stage')} | {where} |")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sp = ap.add_subparsers(dest="cmd", required=True)
    p = sp.add_parser("values"); p.add_argument("--check", action="store_true"); p.set_defaults(fn=cmd_values)
    p = sp.add_parser("check"); p.set_defaults(fn=cmd_check)
    p = sp.add_parser("gen-passwords"); p.add_argument("--out", required=True); p.add_argument("--users"); p.set_defaults(fn=cmd_gen_passwords)
    p = sp.add_parser("conf"); p.add_argument("--passwords", required=True); p.add_argument("--stage", default="B", choices=STAGES)
    p.add_argument("--hash", action="store_true"); p.add_argument("--out"); p.set_defaults(fn=cmd_conf)
    p = sp.add_parser("live"); p.add_argument("--live-conf", required=True); p.add_argument("--passwords", required=True)
    p.add_argument("--stage", default="A1", choices=STAGES); p.add_argument("--out", required=True); p.set_defaults(fn=cmd_live)
    p = sp.add_parser("leaf-local"); p.add_argument("--user", required=True); p.set_defaults(fn=cmd_leaf_local)
    p = sp.add_parser("leaf-conf"); p.add_argument("--user", required=True); p.add_argument("--passwords", required=True)
    p.add_argument("--out", required=True); p.set_defaults(fn=cmd_leaf_conf)
    p = sp.add_parser("secrets"); p.set_defaults(fn=cmd_secrets)
    args = ap.parse_args()
    return args.fn(args)


if __name__ == "__main__":
    sys.exit(main())
