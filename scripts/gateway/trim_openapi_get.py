"""Trim a full OpenAPI document to the read operations the gateway should expose, and write it as a ConfigMap.

agentgateway turns every operation of an OpenAPI target into a tool and cannot include or exclude operations, so the
spec the gateway loads is trimmed in Git. Inputs per target (platform/tool-gateway/openapi/):

  <name>.recipe.yaml   source: file (relative to the recipe), keep: [{method, path, id, params?: [names], limits?: {param: max}}]
  <source file>        the full upstream spec (fetched from the app, or hand-written for apps that publish none)

Output: platform/tool-gateway/manifests/openapi-<name>.configmap.yaml, key `openapi.yaml` (JSON text), which values.yaml mounts under
/specs/<name>/. Run with no arguments to rewrite all, --check to fail on drift (CI runs it through a unit test).
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
DIR = ROOT / "platform/tool-gateway/openapi"
OUT = ROOT / "platform/tool-gateway/manifests"


def _schema(sch: dict) -> dict:
    """Reduce a parameter schema to plain OpenAPI 3.0 keywords: the gateway's parser rejects 3.1 constructs."""
    if not isinstance(sch, dict):
        return {"type": "string"}
    non_null = [s for s in sch.get("anyOf", []) if isinstance(s, dict) and s.get("type") != "null"]
    if non_null:
        sch = {**{k: v for k, v in sch.items() if k != "anyOf"}, **non_null[0]}
    out: dict = {}
    typ = sch.get("type")
    if isinstance(typ, list):
        typ = next((t for t in typ if t != "null"), "string")
    out["type"] = typ if typ in {"string", "integer", "number", "boolean", "array"} else "string"
    for k in ("format", "minimum", "maximum", "default", "enum", "minLength", "maxLength", "pattern"):
        if k in sch and not isinstance(sch[k], (dict, list)) or k == "enum" and k in sch:
            out[k] = sch[k]
    if isinstance(sch.get("exclusiveMinimum"), (int, float)) and not isinstance(sch["exclusiveMinimum"], bool):
        out["minimum"] = sch["exclusiveMinimum"] + (1 if out["type"] == "integer" else 0)
    if out["type"] == "array":
        out["items"] = _schema(sch.get("items") or {})
    return out


def trim(src: dict, keep: list[dict]) -> dict:
    """Keep only the listed GET operations, with plain parameters and a generic response (no components)."""
    out = {"openapi": "3.0.3", "info": {"title": src["info"].get("title", "api"), "version": str(src["info"].get("version", "0"))},
           "paths": {}}
    for k in keep:
        method, path = k["method"].lower(), k["path"]
        if method != "get":
            raise SystemExit(f"{path}: only GET operations may be exposed by a data-group trim")
        orig = src["paths"][path][method]
        names = set(k.get("params", []))
        params = [p for p in orig.get("parameters", []) if p.get("in") == "path" or ("params" not in k) or p.get("name") in names]
        missing = names - {p["name"] for p in params}
        if missing:
            raise SystemExit(f"{path}: parameters {sorted(missing)} not in the source spec")
        outp = []
        for p in params:
            sch = _schema(p.get("schema") or {})
            cap = (k.get("limits") or {}).get(p["name"])
            if cap:
                sch["maximum"] = cap
                sch["default"] = min(sch.get("default", cap), cap)
            q = {"name": p["name"], "in": p["in"], "required": bool(p.get("required")) or p["in"] == "path", "schema": sch}
            desc = (p.get("description") or sch.get("description") or "").strip()
            if desc:
                q["description"] = desc.split("\n")[0][:120]
            outp.append(q)
        op = {"operationId": k["id"], "summary": (orig.get("summary") or k["id"]).strip()[:200], "responses": {"200": {"description": "OK"}}}
        if outp:
            op["parameters"] = outp
        out["paths"].setdefault(path, {})[method] = op
    return out


def configmap(name: str, spec: dict, server: str) -> str:
    spec = {**spec, "servers": [{"url": server}]}
    body = json.dumps(spec, indent=1, sort_keys=True) + "\n"
    head = (f"# GENERATED by scripts/gateway/trim_openapi_get.py from platform/tool-gateway/openapi/{name}.recipe.yaml.\n"
            "# Do not edit; mounted into the gateway pod (values.yaml) as the schema of target `" + name + "`.\n")
    doc = {"apiVersion": "v1", "kind": "ConfigMap",
           "metadata": {"name": f"gateway-openapi-{name}", "namespace": "tool-gateway"},
           "data": {"openapi.yaml": body}}
    class Literal(str):
        pass

    yaml.SafeDumper.add_representer(Literal, lambda d, v: d.represent_scalar("tag:yaml.org,2002:str", v, style="|"))
    doc["data"]["openapi.yaml"] = Literal(body)
    return head + yaml.safe_dump(doc, sort_keys=False, width=1000)


def build() -> dict[Path, str]:
    result = {}
    for recipe_path in sorted(DIR.glob("*.recipe.yaml")):
        recipe = yaml.safe_load(recipe_path.read_text())
        name = recipe_path.name.removesuffix(".recipe.yaml")
        src_path = recipe_path.parent / recipe["source"]
        src = yaml.safe_load(src_path.read_text()) if src_path.suffix in {".yaml", ".yml"} else json.loads(src_path.read_text())
        result[OUT / f"openapi-{name}.configmap.yaml"] = configmap(name, trim(src, recipe["keep"]), recipe["server"])
    return result


def main(argv: list[str]) -> int:
    files = build()
    if "--check" in argv:
        stale = [p.name for p, text in files.items() if not p.exists() or p.read_text() != text]
        if stale:
            print("stale (run scripts/gateway/trim_openapi_get.py):", ", ".join(stale))
            return 1
        return 0
    for p, text in files.items():
        p.write_text(text)
        print("wrote", p.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
