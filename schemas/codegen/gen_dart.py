#!/usr/bin/env python3
"""
gen_dart.py — Generate a typed Dart class from the OneMind event envelope schema.

Usage:
    python3 schemas/codegen/gen_dart.py

Output:
    schemas/codegen/out/envelope.dart

Dependencies: stdlib only (json, pathlib).
Hand-rolls a clean Dart class with fromJson / toJson / copyWith.
"""
import json
from pathlib import Path

HERE = Path(__file__).parent
SCHEMA_FILE = HERE.parent / "envelope" / "envelope.schema.json"
OUT_DIR = HERE / "out"
OUT_FILE = OUT_DIR / "envelope.dart"

OUT_DIR.mkdir(parents=True, exist_ok=True)

with open(SCHEMA_FILE) as f:
    schema = json.load(f)

props = schema.get("properties", {})
required_fields = set(schema.get("required", []))

DART_TYPE_MAP = {
    "string": "String",
    "integer": "int",
    "number": "double",
    "boolean": "bool",
    "object": "Map<String, dynamic>",
    "array": "List<dynamic>",
}

def dart_type(field_name: str, field_schema: dict, is_required: bool) -> str:
    base = DART_TYPE_MAP.get(field_schema.get("type", "object"), "dynamic")
    return base if is_required else f"{base}?"

# Split into required and optional
req_fields = [(k, v) for k, v in props.items() if k in required_fields]
opt_fields = [(k, v) for k, v in props.items() if k not in required_fields]

# Build constructor params
req_params = [f"    required this.{k}," for k, _ in req_fields]
opt_params = [f"    this.{k}," for k, _ in opt_fields]

# Build field declarations
req_decls = []
for k, v in req_fields:
    dt = dart_type(k, v, True)
    desc = v.get("description", "").replace("\n", " ").strip()
    req_decls.append(f"  /// {desc}")
    req_decls.append(f"  final {dt} {k};")

opt_decls = []
for k, v in opt_fields:
    dt = dart_type(k, v, False)
    desc = v.get("description", "").replace("\n", " ").strip()
    opt_decls.append(f"  /// {desc}")
    opt_decls.append(f"  final {dt} {k};")

# fromJson body
from_json_lines = []
for k, v in req_fields:
    dt = dart_type(k, v, True)
    if dt == "Map<String, dynamic>":
        from_json_lines.append(f"      {k}: json['{k}'] as Map<String, dynamic>,")
    elif dt == "int":
        from_json_lines.append(f"      {k}: (json['{k}'] as num).toInt(),")
    elif dt == "double":
        from_json_lines.append(f"      {k}: (json['{k}'] as num).toDouble(),")
    else:
        from_json_lines.append(f"      {k}: json['{k}'] as {dt},")

for k, v in opt_fields:
    dt = dart_type(k, v, False)
    base_dt = dt.rstrip("?")
    if base_dt == "Map<String, dynamic>":
        from_json_lines.append(f"      {k}: json['{k}'] as Map<String, dynamic>?,")
    elif base_dt == "int":
        from_json_lines.append(f"      {k}: json['{k}'] != null ? (json['{k}'] as num).toInt() : null,")
    elif base_dt == "double":
        from_json_lines.append(f"      {k}: json['{k}'] != null ? (json['{k}'] as num).toDouble() : null,")
    else:
        from_json_lines.append(f"      {k}: json['{k}'] as {dt},")

# toJson body
to_json_lines = []
for k, _ in req_fields:
    to_json_lines.append(f"      '{k}': {k},")
for k, _ in opt_fields:
    to_json_lines.append(f"      if ({k} != null) '{k}': {k},")

# copyWith params and body
cw_params = []
cw_body = []
for k, v in req_fields:
    dt = dart_type(k, v, True)
    cw_params.append(f"    {dt}? {k},")
    cw_body.append(f"      {k}: {k} ?? this.{k},")
for k, v in opt_fields:
    dt = dart_type(k, v, False)
    base_dt = dt.rstrip("?")
    cw_params.append(f"    {dt} {k},")
    cw_body.append(f"      {k}: {k} ?? this.{k},")

dart_code = f"""// AUTO-GENERATED by schemas/codegen/gen_dart.py — DO NOT EDIT BY HAND
// Source: schemas/envelope/envelope.schema.json
// Regenerate: python3 schemas/codegen/gen_dart.py
// For use in: onemindos-command/contract/

// ignore_for_file: unnecessary_null_comparison

import 'dart:convert';

/// {schema.get("title", "OneMind Event Envelope")}
///
/// Versioned wrapper for every message on the OneMind NATS bus.
/// All services, agents, bridges, and the Flutter UI speak this envelope.
///
/// Consumers MUST tolerate unknown fields (additionalProperties = true).
/// Pin a minimum [v], never an exact version. Breaking changes bump [v].
class Envelope {{
  // ---- Required fields ----
{chr(10).join(req_decls)}

  // ---- Optional fields ----
{chr(10).join(opt_decls)}

  const Envelope({{
{chr(10).join(req_params)}
{chr(10).join(opt_params)}
  }});

  factory Envelope.fromJson(Map<String, dynamic> json) {{
    return Envelope(
{chr(10).join(from_json_lines)}
    );
  }}

  Map<String, dynamic> toJson() {{
    return {{
{chr(10).join(to_json_lines)}
    }};
  }}

  Envelope copyWith({{
{chr(10).join(cw_params)}
  }}) {{
    return Envelope(
{chr(10).join(cw_body)}
    );
  }}

  @override
  String toString() => jsonEncode(toJson());
}}
"""

OUT_FILE.write_text(dart_code)
print(f"[gen_dart] OK → {OUT_FILE}")
