#!/usr/bin/env python3
"""
gen_python.py — Generate typed Python dataclass from the OneMind event envelope schema.

Usage:
    python3 schemas/codegen/gen_python.py

Output:
    schemas/codegen/out/envelope.py

Dependencies: stdlib only (json, dataclasses, pathlib).
If 'datamodel-code-generator' is installed, uses it for richer output;
otherwise hand-rolls a minimal but correct dataclass.
"""
import json
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).parent
SCHEMA_FILE = HERE.parent / "envelope" / "envelope.schema.json"
OUT_DIR = HERE / "out"
OUT_FILE = OUT_DIR / "envelope.py"

OUT_DIR.mkdir(parents=True, exist_ok=True)

# --- Attempt rich codegen via datamodel-code-generator ---
try:
    result = subprocess.run(
        [
            sys.executable, "-m", "datamodel_code_generator",
            "--input", str(SCHEMA_FILE),
            "--input-file-type", "jsonschema",
            "--output", str(OUT_FILE),
            "--target-python-version", "3.9",
            "--use-standard-collections",
        ],
        capture_output=True, text=True, timeout=60
    )
    if result.returncode == 0:
        print(f"[gen_python] datamodel-code-generator: OK → {OUT_FILE}")
        sys.exit(0)
    else:
        print(f"[gen_python] datamodel-code-generator failed (rc={result.returncode}), falling back to hand-roll.")
        print(result.stderr[:400])
except (ImportError, FileNotFoundError, subprocess.TimeoutExpired) as e:
    print(f"[gen_python] datamodel-code-generator not available ({e}), using built-in emitter.")

# --- Fallback: hand-rolled dataclass emitter ---
with open(SCHEMA_FILE) as f:
    schema = json.load(f)

props = schema.get("properties", {})
required = set(schema.get("required", []))

PYTHON_TYPE_MAP = {
    "string": "str",
    "integer": "int",
    "number": "float",
    "boolean": "bool",
    "object": "Dict[str, Any]",
    "array": "List[Any]",
}

lines = [
    "# AUTO-GENERATED by schemas/codegen/gen_python.py — DO NOT EDIT BY HAND",
    "# Source: schemas/envelope/envelope.schema.json",
    "# Regenerate: python3 schemas/codegen/gen_python.py",
    "",
    "from __future__ import annotations",
    "",
    "from dataclasses import dataclass, field",
    "from typing import Any, Dict, List, Optional",
    "",
    "",
    "@dataclass",
    "class Envelope:",
    f'    """',
    f'    {schema.get("title", "OneMind Event Envelope")}',
    f'    ',
    f'    {schema.get("description", "").splitlines()[0] if schema.get("description") else ""}',
    f'    ',
    f'    Consumers MUST tolerate unknown fields (additionalProperties=True).',
    f'    """',
]

for field_name, field_schema in props.items():
    py_type = PYTHON_TYPE_MAP.get(field_schema.get("type", "object"), "Any")
    description = field_schema.get("description", "")
    is_required = field_name in required

    if not is_required:
        lines.append(f"    # {description}")
        lines.append(f"    {field_name}: Optional[{py_type}] = None")
    else:
        lines.append(f"    # {description}")
        # Required fields need a default to be last — use MISSING sentinel pattern
        # We'll collect required fields first, optional after
        pass

# Re-emit in correct order: required first (no default), optional second (= None)
req_lines = []
opt_lines = []
for field_name, field_schema in props.items():
    py_type = PYTHON_TYPE_MAP.get(field_schema.get("type", "object"), "Any")
    description = field_schema.get("description", "").replace("\n", " ").strip()
    short_desc = description[:100] + ("..." if len(description) > 100 else "")
    is_required = field_name in required

    if is_required:
        req_lines.append(f"    # {short_desc}")
        req_lines.append(f"    {field_name}: {py_type}")
    else:
        opt_lines.append(f"    # {short_desc}")
        opt_lines.append(f"    {field_name}: Optional[{py_type}] = None")

# Rebuild class body cleanly
class_lines = [
    "# AUTO-GENERATED by schemas/codegen/gen_python.py — DO NOT EDIT BY HAND",
    "# Source: schemas/envelope/envelope.schema.json",
    "# Regenerate: python3 schemas/codegen/gen_python.py",
    "",
    "from __future__ import annotations",
    "",
    "from dataclasses import dataclass, field",
    "from typing import Any, Dict, List, Optional",
    "",
    "",
    "@dataclass",
    "class Envelope:",
    '    """',
    f'    {schema.get("title", "OneMind Event Envelope")}',
    "    ",
    "    Versioned wrapper for every message on the OneMind NATS bus.",
    "    Consumers MUST tolerate unknown fields (additionalProperties=True).",
    '    """',
    "",
    "    # ---- Required fields ----",
] + req_lines + [
    "",
    "    # ---- Optional fields ----",
] + opt_lines + [
    "",
    "",
    "# Example factory",
    "def make_envelope(",
    "    v: int,",
    "    id: str,",
    "    ts: str,",
    "    type: str,",
    "    source: str,",
    "    subject: str,",
    "    data: Dict[str, Any],",
    "    **kwargs: Any,",
    ") -> Envelope:",
    '    """Construct an Envelope with required fields; pass optional fields as kwargs."""',
    "    return Envelope(v=v, id=id, ts=ts, type=type, source=source, subject=subject, data=data, **kwargs)",
]

OUT_FILE.write_text("\n".join(class_lines) + "\n")
print(f"[gen_python] hand-rolled emitter: OK → {OUT_FILE}")
