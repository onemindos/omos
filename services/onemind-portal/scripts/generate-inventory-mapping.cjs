// Generates plugins/plugin-onemind-inventory-backend/src/mapping.generated.ts from the reviewed F2
// sources, so the live inventory provider places a new workload exactly where scripts/curate-structure.cjs
// would, without reading catalog/workload-map.yaml at runtime (the mounted catalog ConfigMap only carries
// apps.yaml, cluster.yaml and org.yaml). `--check` fails when the committed file is stale.
const fs = require('node:fs');
const path = require('node:path');
const YAML = require('yaml');

const root = path.resolve(__dirname, '..');
const target = path.join(root, 'plugins/plugin-onemind-inventory-backend/src/mapping.generated.ts');

function buildMapping(base = root) {
  const r = f => YAML.parse(fs.readFileSync(path.join(base, 'catalog', f), 'utf8'));
  const map = r('workload-map.yaml');
  const structure = r('structure.yaml');
  const apps = YAML.parseAllDocuments(fs.readFileSync(path.join(base, 'catalog/apps.yaml'), 'utf8')).map(d => d.toJSON()).filter(Boolean);
  const byName = new Map(apps.filter(e => e.kind === 'Component').map(e => [e.metadata.name, e]));
  const out = {};
  for (const ref of [...new Set(Object.values(map.workloads))].sort()) {
    const name = ref.split('/')[1];
    const app = byName.get(name);
    if (!app) throw new Error(`workload-map target ${ref} has no app Component in apps.yaml`);
    out[name] = {
      title: app.metadata.title,
      system: app.spec.system,
      pillar: app.metadata.labels?.['onemind.io/pillar'] ?? null,
      review: app.metadata.annotations?.['onemind.io/pillar-review'] ?? 'unclassified',
    };
  }
  const unassigned = structure.systems.find(s => s.name === 'unassigned-workloads');
  if (!unassigned) throw new Error('structure.yaml has no unassigned-workloads System');
  const sorted = Object.fromEntries(Object.entries(map.workloads).sort(([a], [b]) => (a < b ? -1 : 1)));
  return { workloads: sorted, apps: out };
}

function render(mapping) {
  const text = [
    '/* eslint-disable */',
    '// Generated by scripts/generate-inventory-mapping.cjs from catalog/workload-map.yaml and catalog/apps.yaml.',
    '// Do not edit by hand: run `node scripts/generate-inventory-mapping.cjs` (a test fails when it is stale).',
    'export interface MappedApp {',
    '  title: string;',
    '  system: string;',
    '  pillar: string | null;',
    '  review: string;',
    '}',
    'export interface InventoryMapping {',
    '  /** "<namespace>/<workload>" (exact, "ns/prefix*" or "ns/*") to the app ref. */',
    '  workloads: Record<string, string>;',
    '  /** App name to the curated presentation of that app. */',
    '  apps: Record<string, MappedApp>;',
    '}',
    `export const mapping: InventoryMapping = ${JSON.stringify(mapping, null, 2)};`,
    '',
  ].join('\n');
  const prettier = require('prettier');
  return prettier.format(text, { ...require('@backstage/cli/config/prettier'), parser: 'typescript' });
}

if (require.main === module) {
  const next = render(buildMapping());
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
    if (current !== next) {
      console.error('mapping.generated.ts is stale: run node scripts/generate-inventory-mapping.cjs');
      process.exit(1);
    }
    console.log('mapping.generated.ts is current');
  } else {
    fs.writeFileSync(target, next);
    console.log(`Wrote ${path.relative(root, target)}`);
  }
}
module.exports = { buildMapping, render, target };
