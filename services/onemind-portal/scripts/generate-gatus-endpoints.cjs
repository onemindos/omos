#!/usr/bin/env node
// Generates platform/gatus/endpoints.yaml from the curated catalog (flagship F7). Every Component with
// `onemind.io/health-check` (the endpoint name) and `onemind.io/health-url` (what to probe) becomes a
// Gatus endpoint. Nothing is typed per app here: add the two annotations to the catalog entry and run
//   node scripts/generate-gatus-endpoints.cjs
// `--check` exits 1 when the committed file is out of date (test-gatus-endpoints.cjs runs the same check).
const fs = require('node:fs');
const path = require('node:path');
const YAML = require('yaml');
const { annotationsOf, hostingKind } = require('./app-contract.cjs');

const ROOT = path.join(__dirname, '../../..');
const CATALOG = path.join(__dirname, '../catalog/apps.yaml');
const OUTPUT = path.join(ROOT, 'platform/gatus/endpoints.yaml');

const isHttps = url => url.startsWith('https://');
// In-cluster services answer fast and are cheap to probe; third-party sites are probed gently.
const INTERVAL = url => (isHttps(url) ? '5m' : '1m');
const CERT_DAYS_CONDITION = '[CERTIFICATE_EXPIRATION] > 336h';

/** Pure: catalog entities to a sorted list of Gatus endpoints. Throws on duplicate names. */
function buildEndpoints(entities) {
  const seen = new Map();
  const endpoints = [];
  for (const entity of entities) {
    if (entity.kind !== 'Component') continue;
    const a = annotationsOf(entity);
    const name = a['onemind.io/health-check'];
    if (!name) continue;
    const url = a['onemind.io/health-url'];
    if (!url) throw new Error(`${entity.metadata.name}: onemind.io/health-check without onemind.io/health-url`);
    if (seen.has(name)) throw new Error(`Gatus endpoint name "${name}" is used by ${seen.get(name)} and ${entity.metadata.name}`);
    seen.set(name, entity.metadata.name);
    const conditions = ['[STATUS] < 400'];
    if (!isHttps(url)) conditions.push('[RESPONSE_TIME] < 3000');
    else conditions.push(CERT_DAYS_CONDITION);
    endpoints.push({ name, group: hostingKind(entity), url, interval: INTERVAL(url), conditions, component: entity.metadata.name });
  }
  return endpoints.sort((x, y) => x.group.localeCompare(y.group) || x.name.localeCompare(y.name));
}

const q = s => JSON.stringify(s);

/** Pure: the endpoint list to the committed YAML text (hand-formatted so the diff is stable). */
function render(endpoints) {
  const lines = [
    '# GENERATED by services/onemind-portal/scripts/generate-gatus-endpoints.cjs from the catalog entries that carry',
    '# onemind.io/health-check and onemind.io/health-url. Do not edit by hand: change the catalog annotations and',
    '# run `node services/onemind-portal/scripts/generate-gatus-endpoints.cjs`. CI fails when this file is stale.',
    'endpoints:',
  ];
  for (const e of endpoints) {
    lines.push(
      `  # catalog component: ${e.component}`,
      `  - name: ${e.name}`,
      `    group: ${e.group}`,
      `    url: ${q(e.url)}`,
      `    interval: ${e.interval}`,
      '    conditions:',
      ...e.conditions.map(c => `      - ${q(c)}`),
    );
  }
  return lines.join('\n') + '\n';
}

function load(file = CATALOG) {
  return fs.readFileSync(file, 'utf8').split(/^---$/m).map(d => YAML.parse(d)).filter(Boolean);
}

function generate(file = CATALOG) {
  return render(buildEndpoints(load(file)));
}

if (require.main === module) {
  const text = generate();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8') : '';
    if (current !== text) {
      console.error('platform/gatus/endpoints.yaml is out of date; run node services/onemind-portal/scripts/generate-gatus-endpoints.cjs');
      process.exit(1);
    }
    console.log('platform/gatus/endpoints.yaml is up to date');
  } else {
    fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });
    fs.writeFileSync(OUTPUT, text);
    console.log(`wrote ${path.relative(ROOT, OUTPUT)}`);
  }
}

module.exports = { buildEndpoints, render, generate, load, OUTPUT, CATALOG };
