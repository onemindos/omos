// Regenerates the token block of src/brand.css from src/tokens.ts.
// Usage (Node 24): node scripts/generate-css.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { buiVariables, cssVariables } from '../src/tokens.ts';

// Backstage renders its toast region with the INVERTED theme mode (a light toast
// on a dark page). The extra [class*='Toast_container'] selectors outrank that
// so toasts follow the portal theme.
const BEGIN = '/* tokens:begin (generated by scripts/generate-css.mjs) */';
const END = '/* tokens:end */';
const block = (sel, vars) =>
  `${sel} {\n${Object.entries(vars)
    .map(([k, v]) => `  ${k}: ${v};`)
    .join('\n')}\n}\n`;
const generated = [
  BEGIN,
  block(":root,\nbody[data-theme-mode='light'],\nbody[data-theme-mode='light'] [class*='Toast_container']", {
    ...cssVariables('light'),
    ...buiVariables('light'),
  }),
  block("body[data-theme-mode='dark'],\nbody[data-theme-mode='dark'] [class*='Toast_container']", {
    ...cssVariables('dark'),
    ...buiVariables('dark'),
  }),
  END,
].join('\n');

const file = new URL('../src/brand.css', import.meta.url);
const css = readFileSync(file, 'utf8');
const re = new RegExp(
  `${BEGIN.replace(/[()*/.]/g, '\\$&')}[\\s\\S]*?${END.replace(
    /[*/]/g,
    '\\$&',
  )}`,
);
if (!re.test(css)) throw new Error('markers missing in brand.css');
writeFileSync(file, css.replace(re, generated));
