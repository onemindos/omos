#!/bin/bash
# update-memory.sh - Update Legacy AI memory/context files
# Usage: ./update-memory.sh "Brief description of changes"

set -e

# Colors for output
GREEN='\033[0;32m'
BLUE='\033[0;34m'
YELLOW='\033[1;33m'
NC='\033[0m' # No Color

# Configuration
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(dirname "$SCRIPT_DIR")"
CONTEXT_DIR="$REPO_ROOT/context"
STATE_DIR="$REPO_ROOT/state"
TIMESTAMP=$(date +%Y-%m-%d-%H%M%S)
DATE=$(date +"%B %d, %Y, %H:%M UTC")

# Ensure directories exist
mkdir -p "$CONTEXT_DIR" "$STATE_DIR"

# Get description from argument or prompt
DESCRIPTION="${1:-}"
if [ -z "$DESCRIPTION" ]; then
    echo -e "${YELLOW}What changed? (Brief description):${NC}"
    read -r DESCRIPTION
fi

echo -e "${BLUE}📝 Updating Legacy AI memory...${NC}"

# Function to get container status
get_container_status() {
    docker ps --format "table {{.Names}}\t{{.Status}}\t{{.Image}}" | grep -v NAMES
}

# Function to get resource usage
get_resource_usage() {
    echo "CPU: $(top -bn1 | grep "Cpu(s)" | awk '{print $2}')%"
    echo "Memory: $(free -h | awk '/^Mem:/ {print $3 "/" $2}')"
    echo "Disk: $(df -h / | awk 'NR==2 {print $5 " used (" $3 "/" $2 ")"}')"
}

# Function to get Tailscale IP
get_tailscale_ip() {
    tailscale ip -4 2>/dev/null || echo "Not configured"
}

# Update CURRENT-STATE.md
echo -e "${BLUE}→ Updating CURRENT-STATE.md${NC}"
cat > "$CONTEXT_DIR/CURRENT-STATE.md" <<EOF
# Current State - Legacy AI Infrastructure

**Last Updated**: $DATE

## Recent Change

$DESCRIPTION

## System Status

### Infrastructure

| Component | Status | Version | Access URL | Notes |
|-----------|--------|---------|------------|-------|
| Cloud VM | ✅ Running | Ubuntu 22.04 | 3.215.29.128 | AWS Lightsail, 4GB RAM |
| Docker | ✅ Running | $(docker --version | cut -d' ' -f3 | tr -d ',') | - | Container runtime |
| Portainer | $(docker ps | grep -q portainer && echo "✅ Running" || echo "❌ Stopped") | Latest | http://portainer.zeusops.dev | Container management |
| Tailscale | $(systemctl is-active tailscale &>/dev/null && echo "✅ Running" || echo "❌ Stopped") | Latest | $(get_tailscale_ip) | VPN mesh |
| Caddy | $(docker ps | grep -q caddy && echo "✅ Running" || echo "❌ Stopped") | Latest | - | Reverse proxy |

### Active Containers

\`\`\`
$(get_container_status)
\`\`\`

### Resource Usage

\`\`\`
$(get_resource_usage)
\`\`\`

### Network Configuration

- **VM Tailscale IP**: $(get_tailscale_ip)
- **MagicDNS**: Enabled
- **Search Domain**: zeusops.dev

### Volumes

\`\`\`
$(docker volume ls)
\`\`\`

### Networks

\`\`\`
$(docker network ls)
\`\`\`

## Recent Changes

### $(date +%Y-%m-%d)

- $DESCRIPTION

---

**Note**: This file is automatically updated by deployment workflows and scripts.
EOF

# Create state snapshot
echo -e "${BLUE}→ Creating state snapshot${NC}"
cat > "$STATE_DIR/$TIMESTAMP.md" <<EOF
# State Snapshot - $TIMESTAMP

## Change

$DESCRIPTION

## Containers

\`\`\`
$(get_container_status)
\`\`\`

## Resource Usage

\`\`\`
$(get_resource_usage)
\`\`\`

## Volumes

\`\`\`
$(docker volume ls)
\`\`\`

## Networks

\`\`\`
$(docker network ls)
\`\`\`

---

Generated by update-memory.sh
EOF

# Commit to Git if in git repo
if git rev-parse --git-dir > /dev/null 2>&1; then
    echo -e "${BLUE}→ Committing to Git${NC}"
    git add "$CONTEXT_DIR/CURRENT-STATE.md" "$STATE_DIR/$TIMESTAMP.md"
    git commit -m "Memory update: $DESCRIPTION" || echo "Nothing to commit"
else
    echo -e "${YELLOW}⚠️  Not in git repository, skipping commit${NC}"
fi

echo -e "${GREEN}✅ Memory updated successfully!${NC}"
echo ""
echo "Updated files:"
echo "  - $CONTEXT_DIR/CURRENT-STATE.md"
echo "  - $STATE_DIR/$TIMESTAMP.md"
echo ""
echo "Current containers:"
get_container_status

# Optional: Show next steps if available
if [ -f "$CONTEXT_DIR/NEXT-STEPS.md" ]; then
    echo ""
    echo "Next steps:"
    grep -A 5 "⏳" "$CONTEXT_DIR/NEXT-STEPS.md" | head -10 || echo "All tasks complete!"
fi
