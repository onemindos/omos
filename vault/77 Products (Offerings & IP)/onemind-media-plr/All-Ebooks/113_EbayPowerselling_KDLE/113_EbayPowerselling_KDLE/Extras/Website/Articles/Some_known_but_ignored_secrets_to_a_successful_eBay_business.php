						Although there is a lot of rubbish for sale on eBay, it is typically sold by individuals who have no intention of developing a successful eBay business in the future.
<br><br>
For serious entrepreneurs, however, selling on eBay can be a good way to start a new business if you are willing to put in the time and energy required to make the business a success. 
<br><br>
eBay is also a good option for existing businesses to expand their reach by selling online. 
<br><br>
Everyone from small used car dealers to big companies like Dell Computers have discovered that eBay is an excellent place to hawk their wares simply due to the huge number of folks who visit the eBay site on a daily basis. 
<br><br>
Nowhere else on earth will you find such a large pool of potential customers. 
<br><br>
However, be aware that eBay is no magic wand. As any eBay Power Seller will tell you, building a successful eBay business takes hard work and requires long hours. Oftentimes, the financial rewards do not also make it worth the effort spent. 
<br><br>
Here are a few tips to help get you started. 
<br><br>
1. Sell quality products.
<br><br>
Do not try to sell junk. Leave the knick-knacks and fake leather jackets to the less informed. Offer only quality products at a fair price. 
<br><br>
2. Research the competition.
<br><br>
Once you have your product in mind, do not invest a dime on inventory until you have spent some time on eBay to see what the competition is doing. 
<br><br>
If you want to sell motorcycle helmets, for example, you should look at current auctions to see how many others are selling similar helmets and what prices they are charging. 
<br><br>
This step is vital since you may discover that you cannot compete with current sellers on price or there is simply no market for what you have to offer. 
<br><br>
3. Start slowly.
<br><br>
Many people believe that the more items they have for sale on eBay the better. They will invest thousands in inventory and spent hundreds on listing fees. Those are the folks that usually end up with ten thousand of items forever stuck on their garage.
<br><br>
4. Test, test and test. 
<br><br>
A fair portion of eBay auctions result in no sales, so it is best to test the waters before jumping in with both feet. 
<br><br>
List a few items and see how they sell. If an item does not sell, list it at least twice more. Some items might not sell the first time, but may the second or third, then sell steadily from then on. 
<br><br>
If an item gets no bids the first time, consider adjusting your price or your terms. If an item sells well, keep it in stock and then experiment with another item. 
<br><br>
5. Do your homework.
<br><br>
eBay is too broad a subject to be covered fully here, but there are a multitude of books available that can help you start a successful eBay business. 
<br><br>
Be aware, however, that eBay is no magic wand. As any eBay Power Seller will tell you, building a successful eBay business takes hard work and requires long hours. Oftentimes, the financial rewards do not make it worth the effort spent.
<br><br>
When it comes down to the mechanics of it all, running an eBay business is no different than running a brick and mortar business. 
<br><br>
You must also consider the legal and accounting aspects of the business. Just because you're selling online does not mean that there are no taxes to be paid. 
<br><br>
Revenue generated by an eBay business is just as reportable and taxable as revenue 
generated as any other kind of business. And if you sell to customers within your state you may also be responsible for collecting city, county or state sales tax. 
<br><br>
One of the biggest obstacles to building a successful eBay business may be the stiffness of the competition. 
<br><br>
Many sellers sell identical items and the price wars often get ugly, but that's to be expected in a free market place, which is exactly what eBay is. 
<br><br>
Thousands of people have done it and have been successful in the eBay business. Can you build a profitable business selling on eBay? Why not take the opportunity and try.
