<p>
What exactly does a dental hygienist do?  Well, depending on the state you live in, the duties vary.  However, all dental hygienists clean people’s teeth and advise them on proper dental care.  Some hygienists also assist the dentist in procedures such as placing fillings in teeth, doing root canals, and examinations.
