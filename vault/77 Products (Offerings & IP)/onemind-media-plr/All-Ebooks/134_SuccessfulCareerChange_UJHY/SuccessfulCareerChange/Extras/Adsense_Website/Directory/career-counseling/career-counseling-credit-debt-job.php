<p>
A credit counseling job is a career that gets people out of debt and back on their feet again.  What you will do is examine a person’s finances and figure out the best way to reduce their debt and improve their financial situation.  This involves working with creditors to negotiate payoff amounts for credit card balances, formulating a budget for your client to follow, and making suggestions as to where they can save money such as reducing their cable bill by canceling movie channels or eliminating excessive entertainment costs by limiting the amount of time they eat outside of the house.
<p>
