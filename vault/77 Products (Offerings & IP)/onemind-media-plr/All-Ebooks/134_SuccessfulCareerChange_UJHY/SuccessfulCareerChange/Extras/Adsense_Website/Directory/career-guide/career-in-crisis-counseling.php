<p>
We are a world in trouble – in crisis, if you will.  The careers that are available in the field of crisis counseling abound, but they take a very unique individual to perform the job.  Having a career in crisis counseling involves a person with a very sympathetic ear as well as the ability to give empathetic advice on an unbiased basis.  Crisis counseling is a very tricky career, so you will have to have a lot of education to provide an effective service to the people who need it the most.
<p>
The first thing you need to do when considering a career in crisis counseling is to take several classes in both clinical psychology as well as sociology and human development.  When you are counseling people who are in crisis, the worst thing you can do is go into the field without the proper training.  Most of the crisis counselors in the business these days have at least a bachelor’s degree, so be prepared to take several classes and be able to achieve your certification.
<p>
However, you can also get a certificate with an associate’s degree that will allow you to have a career in crisis counseling.  That degree will allow you to talk with people and give them some advice that will get them back on their feet and well on their way towards a more healthy life.
<p>
One of the best ways you can get started in a career in crisis counseling is to volunteer at a crisis hotline such as a suicide hotline or an abuse shelter.  When you volunteer at a place like this, they will give you a certain amount of training that will allow you to perform the job properly.  After you have this training, you will be able to pursue further education that will get you a full-time job as a crisis counselor.  Volunteering in places like this will be a stepping stone towards a career that you can be proud of.
<p>
Having a career in crisis counseling can be a very rewarding and satisfying job.  What you need to do is start out small and then work your way up so that you can finally get into a career you love.  If you really want to help people, being a crisis counselor is a great way to begin.  You can get involved with very little training to begin with, but if you want to put forth the effort, you can actually find that a career in crisis counseling could very well be a way to have a satisfying and fulfilling job that you love doing.  

