<br><br>
3.  Property in some regions of France is still extremely cheap compared to other areas of the EU.  As this is more transparent, they predict that more people will want to buy there.  If you are seriously considering buying a holiday home which is also an investment and which will show significant capital growth over the next few years, they recommend that you start your area of search by identifying which French airports have recently become destinations for new air routes, particularly amongst the no frills, cut-price airlines.  If you are not sure yet where you want to buy, decide now not to rush into buying the first property you see.
<br><br>
4.  Start researching the different areas.  You may know already that some areas are unsuitable and you can cross them off your list.  If there are areas you are not sure about, make the decision to visit them before you finalize your search area.  With the increase in low cost air travel, many areas are now within easy reach for a weekend, so go and have a look. If you are extremely familiar with France, I think you will be surprised at just how many wonderful locations there are to choose from, especially those off the well-worn tourist tracks. 
<br><br>
Any research you can do ‘on the ground’ will be worth the time and money spent.  After all, this is a major investment you are thinking of.  It’s worth taking your time to get it right.
<br><br>
5.  Try to view properties early in the year, certainly before July when everyone else is running around looking to buy.  Viewing earlier should give you more choice, and if a vendor is looking for a quick sale, they are more likely to consider offers when the market is quieter.
<br><br>
6.  Don’t make any assumptions about property prices before you start looking.  For example, the south of France has the reputation of being expensive.  It is true that there are many lovely and expensive properties on the Riviera.  However, not every property for sale is a 6-bedroom luxury villa with swimming pool and all mod cons.  There are still plenty of reasonably priced properties to consider if you search around.
<br><br>
They may well be more expensive than their equivalent in other parts of France, but they are still affordable and compared to prices in some parts of London, for example, are still attractive.
<br><br>
7.  The relatively overlooked areas should boom over the next few years as bargains in Brittany, Normandy, the Dordogne, Provence and the Riviera become harder to find.
