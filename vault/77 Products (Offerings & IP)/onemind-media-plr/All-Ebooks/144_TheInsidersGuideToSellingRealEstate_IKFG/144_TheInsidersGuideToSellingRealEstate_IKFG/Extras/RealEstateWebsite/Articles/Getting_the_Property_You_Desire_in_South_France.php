Property buying tips:
<br><br>
1.  The first step in buying a buying a property is to consider why you are buying, and how you can make the most of the investment opportunity.  If you are buying to relocate or for a semi-permanent retirement home, you might not be interested in letting your dream home for extra income.  However, the prospect of benefiting from capital growth can be very appealing.
<br><br>
Alternatively, if you are buying a holiday home for your own occasional use, any extra income from renting will provide a useful contribution to your costs, and might even pay your finance costs.  This would make your dream home a free gift from your tenants!  Whatever your reason for buying, look for a property, which will also be your best investment.
<br><br>
